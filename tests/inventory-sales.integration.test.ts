test("fechas argentinas y validación estricta de ventas", () => {
  assert.equal(salesToday(new Date("2026-11-01T02:59:59Z")), "2026-10-31");
  assert.equal(salesToday(new Date("2026-11-01T03:00:00Z")), "2026-11-01");
  const base = { requestId: randomUUID(), itemId: randomUUID(), fecha: "2024-02-29", unidades: 1, precioUnitARS: 120.55 };
  assert.equal(validateSale(base).fecha, "2024-02-29");
  assert.equal(validateSale({ ...base, fecha: "2025-09" }).fecha, "2025-09");
  assert.match(formatSaleDate("2025-09"), /septiembre de 2025 \(solo mes\)/);
  assert.equal(formatSaleDate("2025-09-12"), "12/09/2025");
  assert.throws(() => validateSale({ ...base, fecha: "9999-01" }));
  assert.throws(() => validateSale({ ...base, fecha: "2025-13" }));
  for (const patch of [{ fecha: "2025-02-29" }, { fecha: "9999-01-01" }, { fecha: "2026-00-01" }, { unidades: 1.5 }, { unidades: 0 }, { precioUnitARS: -1 }, { precioUnitARS: Infinity }, { precioUnitARS: "120" }, { precioUnitARS: 0.001 }, { anterior: "true" }]) assert.throws(() => validateSale({ ...base, ...patch }));
});

test("ventas por mes: transacción, historial, fechas anteriores, concurrencia y acceso privado", { timeout: 120_000 }, async t => {
  const before = { ...process.env };
  const server = createServer();
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const port = (server.address() as { port: number }).port;
  await new Promise<void>(resolve => server.close(() => resolve()));
  const database = new EmbeddedPostgres({ databaseDir: await mkdtemp(join(tmpdir(), "plug-sales-test-")), port, user: "postgres", password: "local-test-only", persistent: false, onLog: () => {}, onError: () => {}, initdbFlags: ["--encoding=UTF8", "--locale=C"], postgresFlags: ["-h", "127.0.0.1"] });
  let pool: import("pg").Pool | undefined;
  try {
    await database.initialise(); await database.start();
    Object.assign(process.env, { PGHOST: "127.0.0.1", PGPORT: String(port), PGUSER: "postgres", PGPASSWORD: "local-test-only", PGDATABASE: "postgres", BUSINESS_APP_ORIGIN: "https://panel.example" });
    const db = await import("../src/lib/db"); pool = db.getPool();
    const sales = await import("../src/lib/inventory-sales-db");
    const item = await db.insertInventoryItem({ nombre: "Remera fixture", cantidadInicial: 5, cantidadVendida: 2, precioVentaARS: 75000, costoUnitARS: 25000, origen: "manual", estado: "en_deposito" });
    let report = await sales.getInventorySalesReport("2025-08");
    assert.deepEqual(report.meses, []);
    assert.equal(report.pendientes[0].unidades, 2);
    const first = { requestId: randomUUID(), itemId: item.id, fecha: "2025-08-31", unidades: 1, precioUnitARS: 65000, anterior: true };
    await sales.recordInventorySale(first);
    await sales.recordInventorySale(first);
    assert.equal((await db.getInventoryItem(item.id))!.cantidadVendida, 2, "backfill must not deduct stock");
    report = await sales.getInventorySalesReport("2025-08");
    assert.equal(report.ventas.length, 1);
    assert.equal(report.meses[0].facturadoARS, 65000);
    assert.equal(report.pendientes[0].unidades, 1);
    await assert.rejects(sales.recordInventorySale({ ...first, precioUnitARS: 66000 }), /otra venta/);
    await assert.rejects(sales.recordInventorySale({ ...first, requestId: randomUUID(), unidades: 2 }), /pendientes/);
    await sales.recordInventorySale({ ...first, requestId: randomUUID(), fecha: "2025-09-01", precioUnitARS: 60000 });
    const current = { requestId: randomUUID(), itemId: item.id, fecha: "2025-09-02", unidades: 2, precioUnitARS: 72000.55 };
    await Promise.all([sales.recordInventorySale(current), sales.recordInventorySale(current)]);
    assert.equal((await db.getInventoryItem(item.id))!.cantidadVendida, 4);
    assert.equal((await db.getInventoryItem(item.id))!.precioVentaARS, 75000, "a sale does not change the catalog price");
    await db.updateInventoryItem(item.id, { precioVentaARS: 99000, costoUnitARS: 50000, nombre: "Nombre cambiado" });
    report = await sales.getInventorySalesReport("2025-09");
    assert.equal(report.meses.find(m => m.mes === "2025-09")!.facturadoARS, 204001.10);
    assert.equal(report.ventas.find(v => v.fecha === "2025-09-02")!.nombre, "Remera fixture");
    assert.equal(report.pendientes.length, 0);
    assert.equal((await sales.getInventorySalesReport("2025-07")).ventas.length, 0);
    await assert.rejects(sales.getInventorySalesReport("2025-13"));
    const race = await Promise.allSettled([1, 2].map(() => sales.recordInventorySale({ ...current, requestId: randomUUID(), unidades: 1 })));
    assert.equal(race.filter(r => r.status === "fulfilled").length, 1);
    assert.equal((await db.getInventoryItem(item.id))!.cantidadVendida, 5);
    assert.equal((await db.getInventoryItem(item.id))!.estado, "agotado");
    const sized = await db.insertInventoryItem({ nombre: "Talles fixture", cantidadInicial: 3, cantidadVendida: 1, talles: [{ talle: "M", cantidadInicial: 1, cantidadVendida: 1 }, { talle: "L", cantidadInicial: 2, cantidadVendida: 0 }], costoUnitARS: 100, precioVentaARS: 400, origen: "manual", estado: "en_deposito" });
    await assert.rejects(sales.recordInventorySale({ ...current, requestId: randomUUID(), itemId: sized.id, unidades: 1 }), /talle/);
    await assert.rejects(sales.recordInventorySale({ ...current, requestId: randomUUID(), itemId: sized.id, unidades: 1, talle: "M" }), /stock/);
    await sales.recordInventorySale({ ...current, requestId: randomUUID(), itemId: sized.id, unidades: 1, talle: "M", anterior: true });
    await sales.recordInventorySale({ ...current, requestId: randomUUID(), itemId: sized.id, unidades: 1, talle: "L" });
    const updated = (await db.getInventoryItem(sized.id))!;
    assert.equal(updated.cantidadVendida, 2);
    assert.equal(updated.talles!.find(t => t.talle === "L")!.cantidadVendida, 1);
    await db.updateInventoryItem(sized.id, { cantidadVendida: 0, talles: [] });
    assert.equal((await sales.getInventorySalesReport("2025-09")).discrepancias, 2);
    const count = Number((await pool.query("SELECT COUNT(*) FROM inventory_sales")).rows[0].count);
    await db.deleteInventoryItem(item.id);
    assert.equal(Number((await pool.query("SELECT COUNT(*) FROM inventory_sales")).rows[0].count), count, "deleting product preserves dated history");
    const cookie = mockAccount(t);
    const route = await import("../src/app/api/inventario/ventas/route");
    const req = (method: string, supplied = cookie, body?: unknown, origin = "https://panel.example") => new Request("https://panel.example/api/inventario/ventas?mes=2025-09", { method, headers: { cookie: supplied, origin, "content-type": "application/json" }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    assert.equal((await route.GET(req("GET", ""))).status, 401);
    assert.equal((await route.POST(req("POST", "", current))).status, 401);
    assert.equal((await route.POST(req("POST", cookie, current, "https://evil.example"))).status, 403);
    assert.equal((await route.POST(req("POST", cookie, { ...current, unidades: 0 }))).status, 400);
    const response = await route.GET(req("GET"));
    assert.equal(response.status, 200); assert.match(response.headers.get("cache-control")!, /private/);
    assert.equal((await route.POST(req("POST", cookie, first))).status, 200, "retries remain safe after product deletion");
    const monthlyItem = await db.insertInventoryItem({ nombre: "Solo mes fixture", cantidadInicial: 1, cantidadVendida: 1, costoUnitARS: 100, precioVentaARS: 55000, estado: "agotado", origen: "manual" });
    const monthSale = { requestId: randomUUID(), itemId: monthlyItem.id, fecha: "2025-10", unidades: 1, precioUnitARS: 55000, anterior: true };
    await sales.recordInventorySale(monthSale); await sales.recordInventorySale(monthSale);
    assert.equal((await db.getInventoryItem(monthlyItem.id))!.cantidadVendida, 1);
    const monthReport = await sales.getInventorySalesReport("2025-10");
    assert.equal(monthReport.ventas.length, 1); assert.equal(monthReport.ventas[0].fecha, "2025-10");
    assert.equal(monthReport.meses.find(m => m.mes === "2025-10")!.facturadoARS, 55000);
    await assert.rejects(sales.recordInventorySale({ ...monthSale, fecha: "2025-10-01" }), /otra venta/);
    assert.equal((await pool.query("SELECT fecha_precision FROM inventory_sales WHERE id=$1", [monthSale.requestId])).rows[0].fecha_precision, "mes");
  } finally { if (pool) await pool.end(); await database.stop(); process.env = before; }
});
