import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

const base = process.env.TEST_BASE_URL || "http://localhost:3001";
const brands = ["Bape", "Supreme", "Corteiz"];
const items = Array.from({ length: 53 }, (_, index) => ({ id: String(index), nombre: `Remera ${String(index + 1).padStart(2, "0")}`, sku: `PLUG-${index}`, marcaId: brands[index % 3], variante: `Color:${index % 2 ? "Blanco" : "Negro"};Talle:${index % 2 ? "L" : "M"}`, estado: index % 5 ? "en_deposito" : "en_transito", origen: index % 2 ? "cssbuy" : "manual", cantidadInicial: 5, cantidadVendida: index % 4, costoUnitARS: 10000, costoUnitUSD: 10, precioVentaARS: 30000 + index * 1000, createdAt: "2026-10-16T12:00:00Z", updatedAt: "2026-10-16T12:00:00Z", talles: null, tienda: null }));
await mkdir(".impeccable/review", { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  for (const width of [1365, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } });
    page.setDefaultTimeout(10000);
    let writes = 0;
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.route("**/api/**", route => {
      const req = route.request(); const path = new URL(req.url()).pathname;
      if (req.method() !== "GET") writes++;
      const body = path === "/api/inventario" ? { items } : path === "/api/marcas" ? { marcas: brands.map(nombre => ({ id: nombre, nombre, activa: true })) } : {};
      return route.fulfill({ contentType: "application/json", body: JSON.stringify(body) });
    });
    const names = () => page.getByRole("button", { name: /^Remera \d+$/ }).allTextContents();
    const pager = page.getByRole("navigation", { name: "Paginación de productos", exact: true });
    await page.goto(`${base}/inventario`);
    await page.getByLabel("Ordenar el inventario").selectOption("nombre");
    assert.equal((await names()).length, 20);
    assert.equal(await pager.getByRole("button", { name: "Anterior", exact: true }).isDisabled(), true);
    await page.getByRole("checkbox", { name: "Seleccionar productos de esta página", exact: true }).check();
    await page.getByText("20 seleccionados en los resultados", { exact: true }).waitFor();
    await pager.getByRole("button", { name: "Siguiente", exact: true }).click();
    await page.getByRole("button", { name: "Remera 21", exact: true }).waitFor();
    assert.equal((await names()).length, 20);
    assert.equal(await page.getByRole("checkbox", { name: "Seleccionar productos de esta página", exact: true }).isChecked(), false);
    await page.getByRole("button", { name: "Seleccionar los 53 resultados", exact: true }).click();
    await pager.getByRole("button", { name: "Página 3", exact: true }).click();
    await page.getByRole("button", { name: "Remera 41", exact: true }).waitFor();
    assert.equal((await names()).length, 13);
    assert.equal(await pager.getByRole("button", { name: "Siguiente", exact: true }).isDisabled(), true);
    assert.equal(await page.getByRole("checkbox", { name: "Seleccionar productos de esta página", exact: true }).isChecked(), true);
    await page.getByLabel("Productos por página").selectOption("50");
    await page.getByRole("button", { name: "Remera 01", exact: true }).waitFor();
    assert.equal((await names()).length, 50);
    await page.getByLabel("Productos por página").selectOption("10");
    assert.equal((await names()).length, 10);
    await page.getByRole("button", { name: "Filtrar por marca", exact: true }).click();
    for (const name of ["Bape", "Supreme"]) await page.getByRole("checkbox", { name, exact: true }).check();
    await page.getByRole("button", { name: "Listo", exact: true }).click();
    assert.equal(await page.getByText("53 seleccionados en los resultados", { exact: true }).count(), 0);
    await page.getByRole("button", { name: "Filtrar por talle", exact: true }).click();
    await page.getByRole("checkbox", { name: "M", exact: true }).check();
    await page.getByRole("button", { name: "Listo", exact: true }).click();
    await page.getByRole("button", { name: "Filtrar por origen", exact: true }).click();
    await page.getByRole("checkbox", { name: "Manual", exact: true }).check();
    await page.getByRole("button", { name: "Listo", exact: true }).click();
    await page.getByLabel("Precio mínimo", { exact: true }).fill("40000");
    await page.getByLabel("Precio máximo", { exact: true }).fill("60000");
    const expected = items.filter(i => ["Bape", "Supreme"].includes(i.marcaId) && i.variante.endsWith("Talle:M") && i.origen === "manual" && i.precioVentaARS >= 40000 && i.precioVentaARS <= 60000).map(i => i.nombre);
    assert.deepEqual(await names(), expected);
    await page.getByRole("button", { name: "Quitar Marca: Bape", exact: true }).waitFor();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: `.impeccable/review/inventory-filters-${width}.png`, fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.getByLabel("Precio máximo", { exact: true }).fill("100");
    await page.getByRole("alert").filter({ hasText: "El precio máximo" }).waitFor();
    await page.getByRole("heading", { name: "Sin resultados", exact: true }).waitFor();
    await page.getByRole("region", { name: "Filtros del inventario", exact: true }).getByRole("button", { name: "Limpiar filtros", exact: true }).click();
    assert.equal((await names()).length, 10);
    await page.getByRole("button", { name: "Filtrar por estado", exact: true }).click();
    await page.getByRole("checkbox", { name: "En tránsito", exact: true }).check();
    await page.getByRole("checkbox", { name: "En depósito", exact: true }).check();
    await page.keyboard.press("Escape");
    await page.getByRole("button", { name: "Quitar Estado: En tránsito", exact: true }).click();
    assert.ok((await names()).every(n => items.find(i => i.nombre === n).estado === "en_deposito"));
    assert.equal(writes, 0);
    assert.deepEqual(errors, []);
    console.log(`${width}px: paginación, selección entre páginas, filtros múltiples, rango y limpieza OK`);
    await page.close();
  }
} finally { await browser.close(); }
